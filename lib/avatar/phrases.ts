/**
 * Выбор сценария. Локальное время клиента; приоритет у содержательных
 * сценариев (день с активностями / пустой вечер) над временем суток.
 */
export function scenarioForNow(
  hour: number,
  activityCount: number,
  mood: Mood,
): DialogScenario {
  if (hour >= 17 && activityCount === 0) return "eveningEmpty";
  if (hour < 12) return "morning";
  if (activityCount >= 2) return "activeDay";
  if (hour >= 12 && hour < 17 && activityCount === 0) return "afternoonEmpty";
  if (mood === "concerned") return "afternoonEmpty";
  return "activeDay";
}

export function phrasesForScenario(scenario: DialogScenario): string[] {
  return PHRASES[scenario] ?? FALLBACK;
}

/** Порядковый номер фразы не должен повторяться подряд при пересборке сценария. */
export function pickPhrase(
  phrases: string[],
  counter: number,
): string {
  if (phrases.length === 0) return FALLBACK[counter % FALLBACK.length];
  return phrases[counter % phrases.length];
}
