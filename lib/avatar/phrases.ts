/**
 * Выбор сценария по фактам. Час неизвестен до монтирования — вызывающий
 * код передаёт 12 как нейтральный полдень. Приоритет: содержательные
 * сценарии (тренировка/изучение/созидание/аскетеза/активный день) важнее
 * времени суток; утверждения фраз всегда соответствуют фактам.
 */
export function scenarioForNow(hour: number, facts: DayFacts, mood: Mood): DialogScenario {
  const activityCount =
    facts.trainingCount +
    facts.learningCount +
    facts.creationCount +
    (facts.nutritionRecorded ? 1 : 0);
  const distinctKinds =
    (facts.trainingCount > 0 ? 1 : 0) +
    (facts.learningCount > 0 ? 1 : 0) +
    (facts.creationCount > 0 ? 1 : 0) +
    (facts.nutritionRecorded ? 1 : 0);

  if (activityCount === 0 && facts.asceticismDone === 0) {
    return hour >= 17 ? "eveningEmpty" : "emptyDay";
  }
  if (hour < 12) return "morning";
  if (activityCount === 0) return "disciplineDay";
  if (distinctKinds >= 2 || activityCount >= 3) return "activeDay";
  if (facts.trainingCount > 0) return "trainingDay";
  if (facts.learningCount > 0) return "learningDay";
  if (facts.creationCount > 0) return "creationDay";
  // Только питание записано: общие фразы о заполненном дне — без конкретики.
  if (mood === "concerned") return "emptyDay";
  return "activeDay";
}

/**
 * Фразы сценария; если аскеза за день отмечена выполненной, в пул
 * добавляются дисциплинарные фразы — они правдивы при любой заполненности.
 */
export function phrasesForScenario(scenario: DialogScenario, facts: DayFacts): string[] {
  const base = PHRASES[scenario] ?? FALLBACK;
  if (facts.asceticismDone > 0 && scenario !== "disciplineDay" && scenario !== "morning") {
    return [...base, ...PHRASES.disciplineDay];
  }
  return base;
}

/** Порядковый номер фразы не должен повторяться подряд при пересборке сценария. */
export function pickPhrase(phrases: string[], counter: number): string {
  if (phrases.length === 0) return FALLBACK[counter % FALLBACK.length];
  return phrases[counter % phrases.length];
}
